#!/usr/bin/env bash
# Reproducible runner-image build (add-cloud-executor 4.3, design D8).
#
# The build reads ONLY versions.lock (digest-pinned base, exact CLI
# versions) -- the intent tags in versions.env never reach it. After a
# successful build the image is secret-scanned (scan-secrets.sh must pass)
# and the resulting tag + config digest are recorded in image.lock; that
# digest is what CLOUD_SANDBOX_RUNNER_IMAGE pins (name@sha256:<digest>),
# and what the agent verifies before every docker run.
#
# Usage:
#   ./build.sh            build from versions.lock, record image.lock
#   ./build.sh --update   resolve versions.env intent into versions.lock
#                         (base digest from the registry; the CLI version
#                         must already be exact -- latest is refused), then build
set -euo pipefail
cd "$(dirname "$0")"

IMAGE_NAME=open-agents-runner

lock_versions() {
  local tag cli
  tag=$(grep -E '^NODE_IMAGE_TAG=' versions.env | cut -d= -f2-)
  cli=$(grep -E '^CLAUDE_CODE_VERSION=' versions.env | cut -d= -f2-)
  [ -n "$tag" ] && [ -n "$cli" ] || { echo "versions.env incomplete" >&2; exit 1; }
  if [ "$cli" = "latest" ] || [ "$cli" = "*" ]; then
    echo "refusing to lock a floating CLI spec ($cli): pin an exact version" >&2
    exit 1
  fi
  # Official (library) images carry no repo prefix in tags but need one in
  # registry paths: node:22-alpine -> v2/library/node/manifests/22-alpine.
  local image path tagpart
  image=$tag
  if [[ "$image" != */* ]]; then image="library/$image"; fi
  path=${image%:*}
  tagpart=${image##*:}
  local token digest
  token=$(curl -fsS "https://auth.docker.io/token?service=registry.docker.io&scope=repository:${path}:pull" \
    | sed -n 's/.*"token":"\([^"]*\)".*/\1/p') \
    || { echo "registry auth failed" >&2; exit 1; }
  digest=$(curl -fsSI -H "Authorization: Bearer $token" \
    -H "Accept: application/vnd.oci.image.index.v1+json, application/vnd.docker.distribution.manifest.list.v2+json" \
    "https://registry-1.docker.io/v2/${path}/manifests/${tagpart}" \
    | tr -d '\r' | awk 'tolower($1)=="docker-content-digest:"{print $2}')
  [ -n "$digest" ] || { echo "could not resolve digest for $tag" >&2; exit 1; }
  {
    echo "# Resolved pins for the runner image (add-cloud-executor 4.3)."
    echo "# GENERATED by ./build.sh --update from versions.env -- do not hand-edit the"
    echo "# digest; re-run --update to move it. The build reads ONLY this file."
    echo "NODE_IMAGE_TAG=${tag}"
    echo "NODE_DIGEST=${digest}"
    echo "CLAUDE_CODE_VERSION=${cli}"
  } > versions.lock
  echo "versions.lock updated: $tag -> $digest, claude-code $cli"
}

[ -f versions.lock ] || { echo "versions.lock missing (run ./build.sh --update first)" >&2; exit 1; }
[ "${1:-}" = "--update" ] && lock_versions

# shellcheck disable=SC1091
source versions.lock
: "${NODE_IMAGE_TAG:?}" "${NODE_DIGEST:?}" "${CLAUDE_CODE_VERSION:?}"

TAG=${TAG:-$(date +%Y-%m-%d)}
docker build \
  --build-arg NODE_IMAGE="${NODE_IMAGE_TAG%%:*}" \
  --build-arg NODE_DIGEST="$NODE_DIGEST" \
  --build-arg CLAUDE_CODE_VERSION="$CLAUDE_CODE_VERSION" \
  -t "$IMAGE_NAME:$TAG" .

# Secret scan BEFORE the image is recorded as usable: a secret that baked in
# must never reach image.lock.
./scan-secrets.sh "$IMAGE_NAME:$TAG"

IMAGE_ID=$(docker image inspect --format '{{.Id}}' "$IMAGE_NAME:$TAG") # sha256:<config digest>
{
  echo "# Built image record (add-cloud-executor 4.3). GENERATED by ./build.sh."
  echo "IMAGE=$IMAGE_NAME:$TAG"
  echo "IMAGE_ID=$IMAGE_ID"
} > image.lock

echo ""
echo "Pin this in CLOUD_SANDBOX_RUNNER_IMAGE:"
echo "  $IMAGE_NAME:$TAG@$IMAGE_ID"
