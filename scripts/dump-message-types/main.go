// dump-message-types prints the bridge's WS dispatch vocabulary as JSON,
// extracted from the LIVE switch statements (AST walk — see
// internal/bridge.ExtractDispatchTypes). Output is consumed by the main
// repo's contracts package (packages/contracts/bridge-message-types.json)
// and reconciled by tests on both sides: if a dispatch case changes without
// regenerating the JSON, internal/bridge/contract_export_test.go and the web
// contracts test both go red. G23 / orchestration-parity rule 3.
//
// Usage (from the bridge repo root):
//
//	go run ./scripts/dump-message-types > ../packages/contracts/bridge-message-types.json
//
// or via `make export-contracts`.
package main

import (
	"encoding/json"
	"fmt"
	"os"

	bridge "github.com/binoctal/open-agents-bridge/internal/bridge"
)

func main() {
	handled, err := bridge.ExtractDispatchTypes("internal/bridge")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	if err := enc.Encode(map[string]any{
		"$comment": "Generated by bridge `make export-contracts` (scripts/dump-message-types). Do not edit by hand: regenerate.",
		"handled":  handled,
	}); err != nil {
		fmt.Fprintln(os.Stderr, "encode:", err)
		os.Exit(1)
	}
}
