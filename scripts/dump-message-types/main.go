// dump-message-types prints the bridge's WS contract vocabularies as JSON:
// the dispatch types (extracted from the LIVE switch statements, see
// internal/bridge.ExtractDispatchTypes) and the AgentStatus constant values
// (internal/bridge.ExtractAgentStatuses). Output is consumed by the main
// repo's contracts package (packages/contracts/bridge-message-types.json)
// and reconciled by tests on both sides: if either vocabulary changes
// without regenerating the JSON, internal/bridge/contract_export_test.go and
// the web contracts test both go red. G23 / orchestration-parity rule 3.
//
// Usage (from the bridge repo root):
//
//	go run ./scripts/dump-message-types > ../packages/contracts/bridge-message-types.json
//
// or via `make export-contracts`.
package main

import (
	"encoding/json"
	"fmt"
	"os"

	bridge "github.com/binoctal/open-agents-bridge/internal/bridge"
)

func main() {
	handled, err := bridge.ExtractDispatchTypes("internal/bridge")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	statuses, err := bridge.ExtractAgentStatuses("internal/protocol")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if len(statuses) == 0 {
		// Guard against a silent extractor regression emptying the pinned
		// vocabulary — parse errors would fail above, but a walk that simply
		// stops matching would zero it out.
		fmt.Fprintln(os.Stderr, "no AgentStatus constants found — extractor broken?")
		os.Exit(1)
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	if err := enc.Encode(map[string]any{
		"$comment":      "Generated by bridge `make export-contracts` (scripts/dump-message-types). Do not edit by hand: regenerate.",
		"handled":       handled,
		"agentStatuses": statuses,
	}); err != nil {
		fmt.Fprintln(os.Stderr, "encode:", err)
		os.Exit(1)
	}
}
